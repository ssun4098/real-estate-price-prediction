import assert from 'node:assert/strict';
import {selectedParcelRegion,parcelSelectionIdentity,comparisonIdentity,invalidateChangedComparisons,comparisonRequest,createComparisonRequestGate} from './src/content/dashboard/comparison-scope.mjs';
const geometry={type:'Polygon',coordinates:[[[127,37.5],[127.001,37.5],[127.001,37.501],[127,37.5]]]};
const parcel=(pnu,name)=>({pnu,legalDongName:name,geometry,sources:[{id:'ned-characteristics',value:pnu}]});
const a=parcel('1165010800113210020','서울특별시 서초구 서초동');
const b=parcel('1165010100100010001','서울특별시 서초구 방배동');
const c=parcel('1165010800113210021','서울특별시 서초구 서초동');
const initial={parcels:[a],comparisonFilters:{sgg:'11650',dong:'서초동',legalDongCode:'1165010800',start:'2025-01',end:'2025-12',scope:'dong',radiusKm:5},unitPlan:[{units:100}],costs:[{amountWon:123}],cashflow:{loan:1},comparables:{landCases:[{id:'oldland'}],revenueCases:[{id:'oldrevenue'}],query:{dong:'서초동'}},sources:[...a.sources,{id:'land'},{id:'applyhome'}]};
assert.equal(selectedParcelRegion([a]).dong,'서초동');
assert.deepEqual(selectedParcelRegion([parcel('4148031020100010001','경기도 파주시 문산읍 선유리')]).dong,'문산읍 선유리');
assert.equal(selectedParcelRegion([]).status,'none');
assert.equal(selectedParcelRegion([a,b]).status,'multiple');
assert.equal(selectedParcelRegion([{pnu:a.pnu,geometry}]).status,'unknown');
const switched=invalidateChangedComparisons(initial,{...initial,parcels:[b]});
assert.equal(switched.comparisonFilters.dong,'방배동');
assert.equal(switched.comparisonFilters.legalDongCode,'1165010100');
assert.equal(switched.comparisonFilters.selectionLinked,true);
assert.equal(switched.comparables.landCases.length,0);
assert.equal(switched.comparables.revenueCases.length,0);
assert.equal(switched.comparables.query,undefined);
assert.deepEqual(switched.sources.map(s=>s.pnu),[b.pnu]);
assert.equal(switched.unitPlan,initial.unitPlan);
assert.equal(switched.costs,initial.costs);
assert.equal(switched.cashflow,initial.cashflow);
assert.equal(switched.selectionReviewRequired,true);
const sameDong=invalidateChangedComparisons(initial,{...initial,parcels:[c]});
assert.notEqual(comparisonIdentity(initial),comparisonIdentity(sameDong));
assert.equal(sameDong.comparables.landCases.length,0);
assert.equal(sameDong.comparables.revenueCases.length,0);
const deselected=invalidateChangedComparisons(initial,{...initial,parcels:[]});
assert.equal(deselected.comparisonFilters.dong,'');
assert.equal(deselected.sources.length,0);
assert.throws(()=>comparisonRequest(deselected),/선택/);
assert.throws(()=>comparisonRequest({...initial,parcels:[a,b]}),/여러 법정동/);
assert.throws(()=>comparisonRequest({...initial,comparisonFilters:{...initial.comparisonFilters,dong:'방배동'}}),/다릅니다/);
assert.equal(comparisonRequest(switched).dong,'방배동');
assert.equal(comparisonRequest(switched).legalDongCode,'1165010100');
assert.equal(parcelSelectionIdentity([a,c]),parcelSelectionIdentity([c,a]));
const resized=invalidateChangedComparisons(initial,{...initial,parcels:[{...a,areaM2:100}]});
assert.equal(resized.comparables,initial.comparables);
const gate=createComparisonRequestGate();
const first=gate.start(comparisonIdentity(initial));
assert.equal(gate.start(comparisonIdentity(initial)),null,'Deduplicate manual and auto requests');
const second=gate.start(comparisonIdentity(switched));
assert.equal(first.controller.signal.aborted,true);
assert.equal(gate.accepts(first,initial),false,'Late old response rejected even with old callback input');
assert.equal(gate.accepts(second,switched),true);
assert.equal(gate.accepts(second,deselected),false,'Fast deselection rejects response');
gate.cancel();
assert.equal(gate.accepts(second,switched),false,'Cancel/load cannot reapply late response');
assert.equal(gate.finish(first),false,'Old request cannot clear current loading');
let resolveOld,resolveNew;
const stale=gate.start(comparisonIdentity(initial));
const oldPromise=new Promise(resolve=>resolveOld=resolve).then(()=>gate.accepts(stale,switched));
const newest=gate.start(comparisonIdentity(switched));
const newPromise=new Promise(resolve=>resolveNew=resolve).then(()=>gate.accepts(newest,switched));
resolveNew();assert.equal(await newPromise,true);resolveOld();assert.equal(await oldPromise,false);
assert.equal(gate.finish(newest),true);
assert.equal(gate.accepts(newest,switched),false,'Finished ticket cannot apply twice');
console.log('parcel linkage: 39 assertions passed');
